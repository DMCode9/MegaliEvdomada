def run():
    target_dir = '/Users/weril/Desktop/web apps/MegaliEvdomada/sequences'
    files = [f for f in os.listdir(target_dir) if f.endswith('.md')]
    
    for f in files:
        filepath = os.path.join(target_dir, f)
        with open(filepath, 'r', encoding='utf-8') as file:
            content = file.read()
            
        new_content = content
        
        # Sort glossary by word length descending so longer words match first
        # (e.g. "κραυγάζοντες" before "κραυγάζοντα" if there are overlaps, though these are different words)
        sorted_glossary = sorted(glossary.items(), key=lambda item: len(item[0]), reverse=True)
        
        for word, translation in sorted_glossary:
            # Negative lookbehind for '[' and negative lookahead for ']' to avoid double wrapping
            pattern = re.compile(rf"(?<!\[)\b({word})\b(?!\])")
            new_content = pattern.sub(rf"[\1]{{{translation}}}", new_content)
            
            # Since some greek words might have different punctuation or accents attached in ways regex misses,
            # this \b boundary is standard but might fail on specific punctuation if not careful.
            # Usually \b works nicely in Python 3.
            
        if new_content != content:
            with open(filepath, 'w', encoding='utf-8') as file:
                file.write(new_content)
            print(f"Updated {f}")

if __name__ == '__main__':
    run()
