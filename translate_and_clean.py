cleaned_data = {}

for k, v in data.items():
    if v == "" and k in new_translations:
        cleaned_data[k] = new_translations[k]
    else:
        cleaned_data[k] = v

final_data = {}
seen_lower = {}
for k, v in cleaned_data.items():
    k_lower = k.lower().strip()
    if k_lower in seen_lower:
        print(f"Case-insensitive duplicate found: '{k}' (already have '{seen_lower[k_lower]}'). Keeping the first.")
    else:
        seen_lower[k_lower] = k
        final_data[k] = v

with open("sequences/glossary.json", "w", encoding="utf-8") as f:
    json.dump(final_data, f, ensure_ascii=False, indent=2)

print("Done. Saved.")
