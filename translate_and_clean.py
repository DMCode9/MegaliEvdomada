import json

with open("sequences/glossary.json", "r", encoding="utf-8") as f:
    text = f.read()

# Custom object pairs hook to just keep first occurrence and note duplicates
def dict_constructor(pairs):
    d = {}
    for k, v in pairs:
        if k in d:
            print(f"Exact duplicate key found and removed: '{k}'")
        else:
            d[k] = v
    return d

data = json.loads(text, object_pairs_hook=dict_constructor)

